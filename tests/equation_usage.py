"""Where each engineering equation is used, generated from the code.

Run from the project folder:

    python tests/equation_usage.py

The equation tags (E1 to E56, with suffixes such as E11a) are read from the
report's Section 2.6. Each one is then looked up in the "Eq." references of
the code comments:

  Reasoning   kb/*.pl and engine/*.pl, except the files below: the knowledge
              base or an inference engine computes or applies it
  Threshold   kb/thresholds.pl and kb/sources.pl: it was used offline to set
              a threshold, and the threshold is what the code applies
  Simulator   simulator/*.py: it generates the synthetic data
  Descriptive none of these: it is part of the engineering model, but no
              code computes it

Writes report/tables/equation_usage.tex and docs/14_equation_usage.md, and
prints the counts as JSON for tests/reproduce.py.
"""

import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BS = chr(92)

THRESHOLD_FILES = {"thresholds.pl", "sources.pl"}
REF = re.compile(r"Eqs?\.\s*(E?\d+[a-z]?(?:\s*(?:,|and|to|-|–)\s*E?\d+[a-z]?)*)")
TAG = re.compile(BS + BS + r"tag\{(E[^}]*)\}")


def report_tags():
    """Equation IDs in tag order. A tag such as E14--E15 holds two IDs."""
    with open(os.path.join(ROOT, "report", "sections", "02_theory_and_kr.tex"), encoding="utf-8") as fh:
        text = fh.read()
    ids = []
    for tag in TAG.findall(text):
        parts = [p.strip() for p in tag.replace("--", "-").split("-")]
        if len(parts) == 2:
            a, b = (int(p.lstrip("E")) for p in parts)
            ids += [f"E{n}" for n in range(a, b + 1)]
        else:
            ids.append(parts[0])
    return ids


def expand(ref):
    """'12-13' -> E12, E13; '31 to 33' -> E31..E33; '5 and 21' -> E5, E21."""
    out = []
    tokens = re.split(r"\s*(,|and|to|-|–)\s*", ref)
    i = 0
    while i < len(tokens):
        tok = tokens[i].lstrip("E")
        if i + 2 < len(tokens) and tokens[i + 1] in ("to", "-", "–") and tok.isdigit():
            hi = tokens[i + 2].lstrip("E")
            out += [f"E{n}" for n in range(int(tok), int(hi) + 1)]
            i += 3
        else:
            if tok and tok not in (",", "and"):
                out.append(f"E{tok}")
            i += 1
    return out


def code_refs():
    """ID -> set of (category, file)."""
    refs = {}
    files = ([(f, "Reasoning") for f in glob.glob(os.path.join(ROOT, "kb", "*.pl"))]
             + [(f, "Reasoning") for f in glob.glob(os.path.join(ROOT, "engine", "*.pl"))]
             + [(f, "Simulator") for f in glob.glob(os.path.join(ROOT, "simulator", "*.py"))])
    for path, cat in files:
        name = os.path.basename(path)
        if name in THRESHOLD_FILES:
            cat = "Threshold"
        with open(path, encoding="utf-8") as fh:
            for m in REF.finditer(fh.read()):
                for eq in expand(m.group(1)):
                    refs.setdefault(eq, set()).add((cat, os.path.relpath(path, ROOT).replace(os.sep, "/")))
    return refs


def classify(ids, refs):
    rows = []
    for eq in ids:
        cats = {c for c, _ in refs.get(eq, ())}
        files = sorted({f for _, f in refs.get(eq, ())})
        rows.append((eq, cats, files))
    return rows


def eq_list(eqs):
    return ", ".join(eqs) if eqs else "none"


def main():
    ids = report_tags()
    rows = classify(ids, code_refs())
    groups = {
        "Reasoning and simulator": [e for e, c, _ in rows if "Reasoning" in c and "Simulator" in c],
        "Reasoning only": [e for e, c, _ in rows if "Reasoning" in c and "Simulator" not in c],
        "Simulator only": [e for e, c, _ in rows if "Simulator" in c and "Reasoning" not in c],
        "Threshold derivation only": [e for e, c, _ in rows if c == {"Threshold"}],
        "Descriptive only": [e for e, c, _ in rows if not c],
    }
    used = len(ids) - len(groups["Descriptive only"])
    in_reasoning = len(groups["Reasoning and simulator"]) + len(groups["Reasoning only"])

    md = ["# Equation Usage", "",
          "Generated by `tests/equation_usage.py` from the `Eq.` references in the code. Do not edit by hand.", "",
          f"{len(ids)} equations are tagged in report Section 2.6. {used} are used by the code: "
          f"{in_reasoning} by the reasoning, the rest by the simulator or to set a threshold. "
          f"{len(groups['Descriptive only'])} are descriptive only.", "",
          "| Group | Count | Equations |", "|---|---|---|"]
    md += [f"| {g} | {len(v)} | {eq_list(v)} |" for g, v in groups.items()]
    md += ["", "## By equation", "", "| Equation | Used by | Files |", "|---|---|---|"]
    md += [f"| {e} | {', '.join(sorted(c)) or 'descriptive'} | {', '.join(f'`{f}`' for f in fs)} |" for e, c, fs in rows]
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "14_equation_usage.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(md) + "\n")

    tex = ["% Generated by tests/equation_usage.py. Do not edit by hand.",
           f"{BS}begin{{table}}[htbp]", f"  {BS}centering", f"  {BS}small",
           f"  {BS}caption{{Where each engineering equation is used, generated from the equation references in the code. "
           f"Reasoning: computed or applied by the knowledge base or an inference engine. Simulator: used to generate the "
           f"synthetic data. Threshold derivation: used offline to set a threshold that the rules apply. Descriptive: part "
           f"of the model, but computed by no code. The file-by-file list is in {BS}texttt{{docs/14{BS}_equation{BS}_usage.md}}.}}",
           f"  {BS}label{{tab:equation-usage}}",
           f"  {BS}begin{{tabular}}{{L{{4.2cm}}rL{{8.4cm}}}}", f"  {BS}toprule",
           f"  Used by & Count & Equations {BS}{BS}", f"  {BS}midrule"]
    tex += [f"  {g} & {len(v)} & {eq_list(v)} {BS}{BS}" for g, v in groups.items()]
    tex += [f"  {BS}midrule", f"  All equations & {len(ids)} & {BS}{BS}",
            f"  {BS}bottomrule", f"  {BS}end{{tabular}}", f"{BS}end{{table}}", ""]
    with open(os.path.join(ROOT, "report", "tables", "equation_usage.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(tex))

    print("JSON " + json.dumps({"equations": len(ids), "used": used, "reasoning": in_reasoning,
                                "descriptive": len(groups["Descriptive only"])}))
    for g, v in groups.items():
        print(f"{g:27} {len(v):3}  {eq_list(v)}")


if __name__ == "__main__":
    main()
