/*  tests/export_latex.pl - writes the diagnostic-rule, threshold and
    provenance tables as LaTeX, straight from the knowledge base, so the
    tables in the report always match the code.

    Run from the project folder:
        swipl -g "export_latex_tables('report/tables')" -t halt main.pl tests/export_latex.pl

    Writes rule_table.tex, threshold_table.tex and provenance_table.tex.
    Each file is a longtable to be \input inside the report.
*/

export_latex_tables(Dir) :-
    make_directory_path(Dir),
    write_table(Dir, 'rule_table.tex', write_rule_table),
    write_table(Dir, 'threshold_table.tex', write_threshold_table),
    write_table(Dir, 'provenance_table.tex', write_provenance_table),
    write_table(Dir, 'maintenance_table.tex', write_maintenance_table),
    format("Wrote LaTeX tables to ~w~n", [Dir]).

write_table(Dir, Name, Writer) :-
    directory_file_path(Dir, Name, File),
    setup_call_cleanup(open(File, write, S, [encoding(utf8)]),
                       ( format(S, "% Generated by tests/export_latex.pl from the knowledge base. Do not edit by hand.~n", []),
                         call(Writer, S) ),
                       close(S)).

write_rule_table(S) :-
    format(S, "\\begin{footnotesize}~n\\begin{longtable}{L{0.9cm}L{4.0cm}L{7.0cm}L{1.9cm}}~n", []),
    format(S, "  \\caption{Diagnostic rules, generated from \\texttt{kb/rules.pl}. In each rule \\texttt{A} is the case being diagnosed and \\texttt{\\textbackslash+} is negation as failure.}\\label{tab:rules}\\\\~n", []),
    table_head(S, "Rule & Concludes & If all of these hold & Source type"),
    forall(drule(Id, Head, Body, Src),
           ( source(Src, Type, _),
             copy_term(Head-Body, H-B),
             numbervars(H-B, 0, _),
             head_parts(H, Kind, HT),
             maplist(goal_tex, B, BTs),
             atomic_list_concat(BTs, ', \\allowbreak ', BodyTex),
             format(S, "  \\texttt{~w} & ~w \\texttt{~w} & \\texttt{~w} & ~w \\\\~n", [Id, Kind, HT, BodyTex, Type]) )),
    format(S, "  \\texttt{r30} & fault \\texttt{normal} & no fault rule fires, and every rack inlet is within the recommended envelope & method \\\\~n", []),
    format(S, "  \\texttt{r31} & \\texttt{unexplained\\_\\allowbreak{}abnormality} & no fault rule fires, but some rack inlet is outside the envelope & method \\\\~n", []),
    format(S, "  \\bottomrule~n\\end{longtable}~n\\end{footnotesize}~n", []).

write_threshold_table(S) :-
    format(S, "\\begin{small}~n\\begin{longtable}{L{4.0cm}L{1.4cm}L{1.5cm}L{3.7cm}L{2.4cm}}~n", []),
    format(S, "  \\caption{Thresholds, generated from \\texttt{kb/thresholds.pl}.}\\label{tab:thresholds}\\\\~n", []),
    table_head(S, "Threshold & Value & Unit & Source & Source type"),
    forall(threshold(N, V, U, Src),
           ( source(Src, Type, _),
             code_escape(N, NE), tex_escape(U, UE), code_escape(Src, SE),
             format(S, "  \\texttt{~w} & ~w & ~w & \\texttt{~w} & ~w \\\\~n", [NE, V, UE, SE, Type]) )),
    format(S, "  \\bottomrule~n\\end{longtable}~n\\end{small}~n", []).

write_provenance_table(S) :-
    format(S, "\\begin{small}~n\\begin{longtable}{L{3.4cm}L{2.4cm}L{8.2cm}}~n", []),
    format(S, "  \\caption{Provenance of rules and thresholds, generated from \\texttt{kb/sources.pl}.}\\label{tab:provenance}\\\\~n", []),
    table_head(S, "Source & Type & Citation or justification"),
    forall(source(Id, Type, Cit),
           ( code_escape(Id, IE), tex_escape(Cit, CE),
             format(S, "  \\texttt{~w} & ~w & ~w \\\\~n", [IE, Type, CE]) )),
    format(S, "  \\bottomrule~n\\end{longtable}~n\\end{small}~n", []).

write_maintenance_table(S) :-
    format(S, "\\begin{footnotesize}~n\\begin{longtable}{L{2.8cm}L{1.3cm}L{8.2cm}L{2.0cm}}~n", []),
    format(S, "  \\caption{Maintenance-action mapping, generated from \\texttt{kb/maintenance.pl}: the corrective plan issued for each diagnosis, in order.}\\label{tab:maintenance}\\\\~n", []),
    table_head(S, "Diagnosis & Priority & Ordered actions & Source"),
    forall(maintenance(Type, Prio, Actions, _, Src),
           ( code_escape(Type, TE), code_escape(Src, SE),
             findall(Item, ( nth1(I, Actions, A), tex_escape(A, AE),
                             format(atom(Item), "~d.~~~w", [I, AE]) ), Items),
             atomic_list_concat(Items, ' \\newline ', ActionsTex),
             format(S, "  \\texttt{~w} & ~w & ~w & \\texttt{~w} \\\\~n", [TE, Prio, ActionsTex, SE]) )),
    format(S, "  \\bottomrule~n\\end{longtable}~n\\end{footnotesize}~n", []).

table_head(S, Header) :-
    format(S, "  \\toprule~n  ~w \\\\~n  \\midrule~n  \\endfirsthead~n", [Header]),
    format(S, "  \\toprule~n  ~w \\\\~n  \\midrule~n  \\endhead~n", [Header]).

head_parts(cond(_, X), condition, T) :- !, term_tex(X, T).
head_parts(fault(_, X), fault, T) :- term_tex(X, T).

goal_tex(G, T) :- term_tex(G, T).

%   term_tex(+Term, -Tex): the term as text, escaped for LaTeX, with a break
%   opportunity after every comma so long goals can wrap.
term_tex(Term, Tex) :-
    format(atom(A), "~W", [Term, [numbervars(true), quoted(false), spacing(next_argument)]]),
    code_escape(A, E),
    atomic_list_concat(Parts, ',', E),
    atomic_list_concat(Parts, ',\\allowbreak{}', Tex).

%   tex_escape(+Text, -Escaped): escape the characters LaTeX treats specially.
tex_escape(Text, Escaped) :-
    atom_chars(Text, Cs),
    maplist(tex_char, Cs, Ps),
    atomic_list_concat(Ps, Escaped).

%   code_escape(+Text, -Escaped): like tex_escape/2, with a line-break
%   opportunity after each underscore, for long names in narrow columns.
code_escape(Text, Escaped) :-
    tex_escape(Text, E0),
    atomic_list_concat(Parts, '\\_', E0),
    atomic_list_concat(Parts, '\\_\\allowbreak{}', Escaped).

tex_char('_', '\\_') :- !.
tex_char('%', '\\%') :- !.
tex_char('&', '\\&') :- !.
tex_char('#', '\\#') :- !.
tex_char('$', '\\$') :- !.
tex_char('{', '\\{') :- !.
tex_char('}', '\\}') :- !.
tex_char('~', '\\textasciitilde{}') :- !.
tex_char('^', '\\textasciicircum{}') :- !.
tex_char('\\', '\\textbackslash{}') :- !.
tex_char(C, C).
