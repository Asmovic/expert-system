"""Variability across held-out seeds (review item B5).

Run from the project folder:

    python tests/seeds.py

The held-out split (seed 777) is one draw of 255 cases. This script generates
four more held-out splits with the same design and different seeds, diagnoses
all five with the four reasoning modes, and reports:

  - exact match per seed, with the mean, standard deviation and range;
  - exact match pooled over the 1275 cases, with Wilson 95% intervals;
  - exact McNemar tests between modes on the pooled, paired cases.

None of the new splits was used to choose anything. Writes data/seeds/,
docs/16_seed_variability.md and report/tables/eval_seeds.tex, and prints
the counts as JSON for tests/reproduce.py.
"""

import json
import os
import statistics
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mismatch import MODES, MODE_NAMES, BS, swipl, wilson, mcnemar, p_text  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NEW_SEEDS = [(1001, "ra"), (2002, "rb"), (3003, "rc"), (4004, "rd")]
SEEDS = [777] + [s for s, _ in NEW_SEEDS]
PAIRS = [("deductive", "ded_abd"), ("deductive", "ded_cbd"), ("deductive", "full"),
         ("ded_abd", "ded_cbd"), ("ded_abd", "full"), ("ded_cbd", "full")]


def split_of(seed):
    return "holdout" if seed == 777 else f"seed{seed}"


def generate():
    os.makedirs(os.path.join(ROOT, "data", "seeds"), exist_ok=True)
    for seed, prefix in NEW_SEEDS:
        base = os.path.join("data", "seeds", f"holdout_{seed}")
        subprocess.run([sys.executable, "-I", "simulator/dc_sim.py", "--seed", str(seed), "--prefix", prefix,
                        "--split", split_of(seed), "--out", base + ".pl", "--csv", base + ".csv",
                        "--truth", base + ".json"], cwd=ROOT, check=True, capture_output=True, text=True)


def diagnose():
    files = ", ".join(f"'data/seeds/holdout_{s}.pl'" for s, _ in NEW_SEEDS)
    splits = ", ".join(split_of(s) for s in SEEDS)
    goal = (f"load_files([{files}], []), "
            f"forall(( member(Sp, [{splits}]), case_split(C, Sp), member(M, [deductive, ded_abd, ded_cbd, full]) ), "
            f"( expected(C, E0), msort(E0, E), diagnose_mode(M, C, G0), msort(G0, G), "
            f"( E == G -> O = 1 ; O = 0 ), format(\"ROW ~w ~w ~w ~w~n\", [Sp, C, M, O]) ))")
    out = subprocess.run([swipl(), "-q", "-g", goal, "-t", "halt", "main.pl"],
                         cwd=ROOT, check=True, capture_output=True, text=True).stdout
    rows = {}
    for line in out.splitlines():
        if line.startswith("ROW "):
            _, sp, case, mode, ok = line.split()
            rows[(sp, case, mode)] = int(ok)
    return rows


def tables(rows):
    """per[(seed, mode)] = correct; paired[mode] = list of 0/1 over all cases in a fixed order."""
    cases = sorted({(sp, c) for sp, c, _ in rows})
    per = {(s, m): sum(rows[(split_of(s), c, m)] for sp, c in cases if sp == split_of(s)) for s in SEEDS for m in MODES}
    n = {s: sum(1 for sp, _ in cases if sp == split_of(s)) for s in SEEDS}
    paired = {m: [rows[(sp, c, m)] for sp, c in cases] for m in MODES}
    return per, n, paired


def write_outputs(per, n, paired):
    total = len(paired["full"])
    pct = lambda k, nn: 100 * k / nn
    md = ["# Variability Across Held-Out Seeds", "",
          "Generated by `tests/seeds.py`. Do not edit by hand. Every case is synthetic.", "",
          f"Five held-out splits of {n[777]} cases with the same design: seed 777 (the reported held-out split) and "
          f"seeds {', '.join(str(s) for s, _ in NEW_SEEDS)}. None was used to choose anything.", "",
          "## Exact match per seed", "",
          "| Mode | " + " | ".join(f"Seed {s}" for s in SEEDS) + " | Mean | SD | Range | Pooled (95% CI) |",
          "|---" * (len(SEEDS) + 5) + "|"]
    tex = ["% Generated by tests/seeds.py. Do not edit by hand.",
           f"{BS}begin{{table}}[htbp]", f"  {BS}centering", f"  {BS}footnotesize", f"  {BS}setlength{{{BS}tabcolsep}}{{4pt}}",
           f"  {BS}caption{{Exact match on five held-out splits of {n[777]} cases with different seeds. Seed 777 is the "
           f"held-out split reported in Table~{BS}ref{{tab:modes-holdout}}. SD: sample standard deviation over the five "
           f"seeds. Pooled: all {total} cases, with the Wilson 95{BS}% confidence interval.}}",
           f"  {BS}label{{tab:seeds}}",
           f"  {BS}begin{{tabular}}{{L{{5.0cm}}" + "r" * len(SEEDS) + "rrc}", f"  {BS}toprule",
           "  Mode & " + " & ".join(str(s) for s in SEEDS) + f" & Mean & SD & Pooled (95{BS}% CI) {BS}{BS}",
           f"  {BS}midrule"]
    summary = {}
    for m in MODES:
        vals = [pct(per[(s, m)], n[s]) for s in SEEDS]
        mean, sd = statistics.mean(vals), statistics.stdev(vals)
        k = sum(paired[m])
        lo, hi = wilson(k, total)
        summary[m] = (mean, sd, min(vals), max(vals), k)
        md.append(f"| {MODE_NAMES[m]} | " + " | ".join(f"{v:.1f}%" for v in vals)
                  + f" | {mean:.1f}% | {sd:.1f} | {min(vals):.1f} to {max(vals):.1f}% | "
                  f"{pct(k, total):.1f}% ({lo * 100:.1f} to {hi * 100:.1f}) |")
        tex.append(f"  {MODE_NAMES[m]} & " + " & ".join(f"{v:.1f}" for v in vals)
                   + f" & {mean:.1f} & {sd:.1f} & {pct(k, total):.1f} ({lo * 100:.1f}--{hi * 100:.1f}) {BS}{BS}")
    tex += [f"  {BS}bottomrule", f"  {BS}end{{tabular}}", f"{BS}end{{table}}", ""]

    md += ["", f"## Paired comparison, pooled over {total} cases", "",
           "Exact two-sided McNemar test on the cases where two modes disagree.", "",
           "| Mode A | Mode B | Only A right | Only B right | p |", "|---|---|---|---|---|"]
    tex += [f"{BS}begin{{table}}[htbp]", f"  {BS}centering", f"  {BS}small",
            f"  {BS}caption{{Paired comparison of reasoning modes pooled over the five held-out seeds ({total} cases): "
            f"exact two-sided McNemar test on the cases where the two modes disagree.}}",
            f"  {BS}label{{tab:seeds-significance}}",
            f"  {BS}begin{{tabular}}{{L{{4.85cm}}L{{4.85cm}}rrr}}", f"  {BS}toprule",
            f"  Mode A & Mode B & Only A & Only B & $p$ {BS}{BS}", f"  {BS}midrule"]
    pvals = {}
    for a, b in PAIRS:
        oa, ob, p = mcnemar(paired[a], paired[b])
        pvals[f"{a}|{b}"] = (oa, ob, p)
        md.append(f"| {MODE_NAMES[a]} | {MODE_NAMES[b]} | {oa} | {ob} | {p_text(p)} |")
        pt = p_text(p, True)
        tex.append(f"  {MODE_NAMES[a]} & {MODE_NAMES[b]} & {oa} & {ob} & "
                   + (f"{BS}textbf{{{pt}}}" if p < 0.05 else pt) + f" {BS}{BS}")
    tex += [f"  {BS}bottomrule", f"  {BS}end{{tabular}}", f"{BS}end{{table}}", ""]

    with open(os.path.join(ROOT, "docs", "16_seed_variability.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(md) + "\n")
    with open(os.path.join(ROOT, "report", "tables", "eval_seeds.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(tex))
    return summary, pvals


def main():
    generate()
    per, n, paired = tables(diagnose())
    summary, pvals = write_outputs(per, n, paired)
    print("JSON " + json.dumps({"per_seed": {f"{s}|{m}": per[(s, m)] for s in SEEDS for m in MODES},
                                "pooled": {m: summary[m][4] for m in MODES}}))
    for m in MODES:
        mean, sd, lo, hi, k = summary[m]
        print(f"{m:9}  mean {mean:.1f}%  sd {sd:.1f}  range {lo:.1f}-{hi:.1f}  pooled {k}/{len(paired[m])}")
    for pair, (oa, ob, p) in pvals.items():
        print(f"{pair:20} {oa:3} {ob:3}  p = {p_text(p)}")


if __name__ == "__main__":
    main()
