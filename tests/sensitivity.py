"""Stage 14 sensitivity analysis driver.

Generates one synthetic dataset per sweep level with simulator/dc_sim.py,
asks Prolog (tests/sensitivity.pl) to diagnose it in all four reasoning
modes, and writes:

    docs/10_sensitivity_results.md          sweep tables
    docs/10b_threshold_sensitivity.md       threshold perturbation tables
    report/figures/sens_<kind>.tex          pgfplots figures for the report
    data/sweeps/results.json                raw metrics

Python only generates data and formats results. All diagnosis runs in Prolog.

Usage, from the project folder:
    python tests/sensitivity.py
"""

import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "simulator"))
import dc_sim  # noqa: E402

SEEDS = {"noise": 4242, "missing": 4343, "multi": 4444, "bias": 4545}
N_CASES = 60
MODES = ["deductive", "ded_abd", "ded_cbd", "full"]
MODE_NAMES = {"deductive": "Deductive only", "ded_abd": "Deductive + abductive",
              "ded_cbd": "Deductive + consistency-based", "full": "Complete system"}
LEVEL_LABEL = {"noise": "Noise multiple", "missing": "Readings removed", "multi": "Simultaneous faults",
               "bias": "Sensor bias (K)"}
TITLES = {"noise": "Sensor noise", "missing": "Missing observations",
          "multi": "Multiple simultaneous faults", "bias": "Contradictory evidence: sensor bias size"}

# Validated categorical palette (dataviz reference, slots 1 to 4, light mode).
# Marker shape and dash pattern repeat the identity so colour is never alone.
STYLE = {
    "deductive": ("2a78d6", "*", "solid"),
    "ded_abd":   ("eb6834", "square*", "dashed"),
    "ded_cbd":   ("1baf7a", "triangle*", "dotted"),
    "full":      ("eda100", "diamond*", "dashdotted"),
}


def swipl():
    exe = shutil.which("swipl")
    if exe:
        return exe
    fallback = r"C:\Program Files\swipl\bin\swipl.exe"
    if os.path.exists(fallback):
        return fallback
    sys.exit("swipl not found on PATH")


def prolog(goal_list):
    cmd = [swipl(), "-q"]
    for g in goal_list:
        cmd += ["-g", g]
    cmd += ["-t", "halt", "main.pl", "tests/metrics.pl", "tests/sensitivity.pl"]
    out = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, check=True)
    return out.stdout


def run_sweeps():
    results = {}
    os.makedirs(os.path.join(ROOT, "data", "sweeps"), exist_ok=True)
    for kind, (levels, _) in dc_sim.SWEEPS.items():
        results[kind] = []
        for level in levels:
            stem = f"{kind}_{level}".replace(".", "p")
            pl = os.path.join("data", "sweeps", f"{stem}.pl")
            cases = dc_sim.generate_sweep(kind, level, SEEDS[kind], N_CASES)
            dc_sim.write_prolog(cases, os.path.join(ROOT, pl), SEEDS[kind], "sweep")
            out = prolog([f"load_files(['{pl.replace(os.sep, '/')}'], [])", "sweep_metrics(sweep)"])
            rows = [json.loads(line[5:]) for line in out.splitlines() if line.startswith("JSON ")]
            results[kind].append({"level": level, "modes": {r["mode"]: r for r in rows}})
            print(f"{kind} {level}: " + ", ".join(f"{r['mode']} {r['exact']:.2f}" for r in rows))
    return results


def fmt_level(kind, level):
    if kind == "missing":
        return f"{level * 100:.0f}%"
    if kind == "multi":
        return f"{int(level)}"
    return f"{level:g}"


def write_tables(results, path):
    lines = ["# Stage 14: Sensitivity Results", "",
             "Generated by `tests/sensitivity.py`. Do not edit by hand. Every case is synthetic.", "",
             f"Each sweep point has {N_CASES} new cases from `simulator/dc_sim.py`. One seed is used for all levels of a sweep, so neighbouring levels differ mainly in the swept factor.", "",
             "Exact match is the share of cases whose predicted fault set equals the true set. Macro F1 averages over the fault classes present in that sweep.", ""]
    for kind, points in results.items():
        _, desc = dc_sim.SWEEPS[kind]
        lines += [f"## {TITLES[kind]}", "", f"The level is the {desc}.", "",
                  f"Exact match by reasoning mode. Figure: `report/figures/sens_{kind}.tex`.", "",
                  "| " + LEVEL_LABEL[kind] + " | " + " | ".join(MODE_NAMES[m] for m in MODES) + " |",
                  "|---" * (len(MODES) + 1) + "|"]
        for p in points:
            cells = [f"{p['modes'][m]['exact'] * 100:.1f}%" for m in MODES]
            lines.append(f"| {fmt_level(kind, p['level'])} | " + " | ".join(cells) + " |")
        lines += ["", "Complete system in detail:", "",
                  "| " + LEVEL_LABEL[kind] + " | Exact match | Coverage | Macro precision | Macro recall | Macro F1 | PlanValidity | Mean time (ms) | Max time (ms) |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for p in points:
            r = p["modes"]["full"]
            lines.append(f"| {fmt_level(kind, p['level'])} | {r['exact']*100:.1f}% | {r['coverage']*100:.1f}% | "
                         f"{r['precision']:.3f} | {r['recall']:.3f} | {r['f1']:.3f} | {r['plan_validity']*100:.1f}% | "
                         f"{r['mean_ms']:.2f} | {r['max_ms']:.2f} |")
        lines.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def write_figure(kind, points, path, metric="exact", ylabel="Exact match (\\%)", scale=100.0, ymax=100):
    xs = [p["level"] * (100 if kind == "missing" else 1) for p in points]
    xlabel = LEVEL_LABEL[kind] + (" (\\%)" if kind == "missing" else "")
    out = ["% Generated by tests/sensitivity.py. Do not edit by hand.",
           "% Needs \\usepackage{pgfplots} and \\pgfplotsset{compat=1.18} in the preamble.",
           "% Colours: validated categorical palette, slots 1 to 4. Marker and dash repeat the identity.",
           "\\begin{tikzpicture}"]
    for m in MODES:
        out.append(f"\\definecolor{{mode{m.replace('_', '')}}}{{HTML}}{{{STYLE[m][0]}}}")
    ylim = f"ymin=0, ymax={ymax}," if ymax else "ymin=0,"
    out += ["\\begin{axis}[",
            "  width=0.92\\linewidth, height=6cm,",
            f"  xlabel={{{xlabel}}}, ylabel={{{ylabel}}},",
            f"  {ylim}",
            f"  xtick={{{','.join(f'{x:g}' for x in xs)}}},",
            "  grid=major, major grid style={line width=0.2pt, draw=black!12},",
            "  axis line style={draw=black!45}, tick style={draw=black!45},",
            "  label style={font=\\small}, tick label style={font=\\footnotesize},",
            "  legend style={font=\\footnotesize, draw=none, fill=none, at={(0.5,1.03)}, anchor=south, legend columns=2,",
            "    /tikz/every even column/.append style={column sep=1.2em}},",
            "  legend cell align=left,",
            "]"]
    for m in MODES:
        col, mark, dash = STYLE[m]
        coords = " ".join(f"({x:g},{p['modes'][m][metric] * scale:.2f})" for x, p in zip(xs, points))
        out.append(f"\\addplot[color=mode{m.replace('_', '')}, {dash}, line width=1pt, mark={mark}, mark size=2.2pt, "
                   f"mark options={{solid, draw=white, line width=0.4pt}}] coordinates {{{coords}}};")
        out.append(f"\\addlegendentry{{{MODE_NAMES[m]}}}")
    out += ["\\end{axis}", "\\end{tikzpicture}", ""]
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))


def main():
    os.chdir(ROOT)
    results = run_sweeps()
    with open(os.path.join(ROOT, "data", "sweeps", "results.json"), "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=1)
    write_tables(results, os.path.join(ROOT, "docs", "10_sensitivity_results.md"))
    figdir = os.path.join(ROOT, "report", "figures")
    os.makedirs(figdir, exist_ok=True)
    for kind, points in results.items():
        write_figure(kind, points, os.path.join(figdir, f"sens_{kind}.tex"))
    write_figure("multi", results["multi"], os.path.join(figdir, "sens_multi_time.tex"),
                 metric="mean_ms", ylabel="Mean reasoning time (ms)", scale=1.0, ymax=None)
    print("Running the threshold sweep on the held-out split...")
    print(prolog(["threshold_sweep('docs/10b_threshold_sensitivity.md')"]).strip())
    print("Done.")


# ---------------------------------------------------------------------------
# LaTeX tables for the report. Also usable alone:
#     python tests/sensitivity.py --tables-only
# BS is one backslash, written out once so the LaTeX below stays readable.
# ---------------------------------------------------------------------------
BS = "\\"
TEX_MODE_HEAD = "Ded. & +Abd. & +Cons. & Complete"
ROW_END = f" {BS}{BS}"
CAPTION_SUBJECT = {"noise": "sensor noise", "missing": "missing observations",
                   "multi": "the number of simultaneous faults",
                   "bias": "the size of a sensor bias, a source of contradictory evidence"}


def tex_level(kind, level):
    if kind == "missing":
        return f"{level * 100:.0f}{BS}%"
    if kind == "bias":
        return f"{level:g}{BS},K"
    if kind == "multi":
        return f"{int(level)}"
    return f"{level:g}"


def write_latex_sweeps(results, tex_dir):
    os.makedirs(tex_dir, exist_ok=True)
    for kind, points in results.items():
        head = LEVEL_LABEL[kind].replace("(K)", "").strip()
        lines = ["% Generated by tests/sensitivity.py. Do not edit by hand.",
                 f"{BS}begin{{table}}[htbp]", f"  {BS}centering", f"  {BS}footnotesize",
                 f"  {BS}setlength{{{BS}tabcolsep}}{{4pt}}",
                 f"  {BS}caption{{Sensitivity to {CAPTION_SUBJECT[kind]}: exact match by reasoning mode, "
                 f"with coverage, macro F1 and mean time in milliseconds of the complete system. "
                 f"Each level has {N_CASES} synthetic cases. Ded.: deductive only; +Abd.: deductive and "
                 f"abductive; +Cons.: deductive and consistency-based; Cov.: coverage.}}",
                 f"  {BS}label{{tab:sens-{kind}}}",
                 f"  {BS}begin{{tabular}}{{lrrrrrrr}}", f"  {BS}toprule",
                 f"  {head} & {TEX_MODE_HEAD} & Cov. & Macro F1 & ms{ROW_END}",
                 f"  {BS}midrule"]
        for p in points:
            ex = " & ".join(f"{p['modes'][m]['exact'] * 100:.1f}{BS}%" for m in MODES)
            f = p["modes"]["full"]
            lines.append(f"  {tex_level(kind, p['level'])} & {ex} & {f['coverage'] * 100:.1f}{BS}% & "
                         f"{f['f1']:.3f} & {f['mean_ms']:.2f}{ROW_END}")
        lines += [f"  {BS}bottomrule", f"  {BS}end{{tabular}}", f"{BS}end{{table}}", ""]
        with open(os.path.join(tex_dir, f"sens_{kind}_table.tex"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(lines))


def write_latex_thresholds(md_path, tex_path):
    """Converts the generated threshold-sensitivity Markdown into one LaTeX table."""
    with open(md_path, encoding="utf-8") as fh:
        text = fh.read()
    rows = {}
    for sec in text.split("\n## ")[1:]:
        which = "ded" if sec.startswith("Deductive") else "full"
        for line in sec.splitlines():
            if line.startswith("| ") and not line.startswith("| Threshold"):
                cells = [c.strip() for c in line.strip("|").split("|")]
                rows.setdefault(cells[0], {"base": cells[1]})[which] = cells[3:7]
    dot = f"${BS}cdot$"
    header = f"  Threshold & Base & $-2$ / 0.8 & $-1$ / 0.9 & $+1$ / 1.1 & $+2$ / 1.2 & Ded. worst{ROW_END}"
    out = ["% Generated by tests/sensitivity.py from docs/10b_threshold_sensitivity.md. Do not edit by hand.",
           f"{BS}begin{{footnotesize}}", f"{BS}setlength{{{BS}tabcolsep}}{{4pt}}",
           f"{BS}begin{{longtable}}{{L{{4.4cm}}L{{1.6cm}}rrrrr}}",
           f"  {BS}caption{{Threshold sensitivity on the held-out split: change in exact-match accuracy of the "
           f"complete system, in percentage points, when one threshold is perturbed. Temperature thresholds move "
           f"by $-2$, $-1$, $+1$ and $+2${BS},K; other thresholds are scaled by 0.8, 0.9, 1.1 and 1.2. The last "
           f"column is the worst change for deduction alone. A dot means no change.}}"
           f"{BS}label{{tab:sens-thresholds}}{BS}{BS}",
           f"  {BS}toprule", header, f"  {BS}midrule", f"  {BS}endfirsthead",
           f"  {BS}toprule", header, f"  {BS}midrule", f"  {BS}endhead"]
    for name, r in rows.items():
        cells = [dot if c == "." else c for c in r["full"]]
        ded = [float(c) for c in r["ded"] if c not in (".", "")]
        worst = f"{min(ded):.1f}" if ded and min(ded) < 0 else dot
        base = (r["base"].replace("degC", f"{BS}textdegree C").replace("kelvin", "K")
                .replace("percent", f"{BS}%").replace("ratio", "").strip())
        tname = name.replace("_", f"{BS}_{BS}allowbreak{{}}")
        out.append(f"  {BS}texttt{{{tname}}} & {base} & " + " & ".join(cells) + f" & {worst}{ROW_END}")
    out += [f"  {BS}bottomrule", f"{BS}end{{longtable}}", f"{BS}end{{footnotesize}}", ""]
    with open(tex_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))


def tables_only():
    os.chdir(ROOT)
    with open(os.path.join(ROOT, "data", "sweeps", "results.json"), encoding="utf-8") as fh:
        results = json.load(fh)
    tex_dir = os.path.join(ROOT, "report", "tables")
    write_latex_sweeps(results, tex_dir)
    write_latex_thresholds(os.path.join(ROOT, "docs", "10b_threshold_sensitivity.md"),
                           os.path.join(tex_dir, "sens_threshold_table.tex"))
    print("Wrote sensitivity tables to report/tables")


if __name__ == "__main__":
    if "--tables-only" in sys.argv:
        tables_only()
    else:
        main()
        tables_only()
