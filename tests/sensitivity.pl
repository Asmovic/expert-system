/*  tests/sensitivity.pl - Stage 14 sensitivity analysis, Prolog side.

    tests/sensitivity.py drives this file. It can also be used directly:

    sweep_metrics(+Split)
      Runs the four reasoning modes on every case in Split and prints one
      line per mode, starting with "JSON ", holding the metrics.

    threshold_sweep(+File)
      Perturbs each diagnostic threshold in turn on the held-out split and
      writes the change in exact-match accuracy to File as Markdown.
      Temperatures move by -2, -1, +1 and +2 K. Other thresholds are scaled
      by 0.8, 0.9, 1.1 and 1.2.

        swipl -g "threshold_sweep('docs/10b_threshold_sensitivity.md')" -t halt main.pl tests/metrics.pl tests/sensitivity.pl
*/

sweep_metrics(Split) :-
    modes(Ms),
    forall(member(M, Ms),
           ( run_mode(M, Split, Rs),
             emr(Rs, E), coverage(Rs, Cv), macro_prf_present(Rs, P, R, F),
             times(Rs, Tm, Tx), plan_validity(Rs, PV), length(Rs, N),
             format("JSON {\"mode\": \"~w\", \"n\": ~d, \"exact\": ~4f, \"coverage\": ~4f, \"precision\": ~4f, \"recall\": ~4f, \"f1\": ~4f, \"mean_ms\": ~4f, \"max_ms\": ~4f, \"plan_validity\": ~4f}~n",
                    [M, N, E, Cv, P, R, F, Tm, Tx, PV]) )).

%   Macro averages over the classes that occur in the expected labels, so
%   a sweep that never contains a class is not penalised for it.
macro_prf_present(Rs, MP, MR, MF) :-
    findall(K, ( member(r(_, _, E, _, _), Rs), member(L, E), label_class(L, K) ), K0),
    sort(K0, Ks),
    findall(P-R-F, ( member(K, Ks), class_counts(Rs, K, TP, FP, FN), prf(TP, FP, FN, P, R, F) ), Ts),
    findall(P, member(P-_-_, Ts), Ps), mean(Ps, MP),
    findall(R, member(_-R-_, Ts), Rr), mean(Rr, MR),
    findall(F, member(_-_-F, Ts), Fs), mean(Fs, MF).

perturbable(Name, Kind) :-
    threshold(Name, _, Unit, _),
    Name \== t_supply_setpoint,          % a design value, not a diagnostic limit
    (   memberchk(Unit, [degC, kelvin]), Name \== sensor_noise_floor
    ->  Kind = offset          % a temperature limit moves by whole kelvin
    ;   Kind = factor          % ratios, rates, and the noise floor scale
    ).

levels(offset, [-2.0, -1.0, 1.0, 2.0]).
levels(factor, [0.8, 0.9, 1.1, 1.2]).

set_perturbation(Name, offset, D) :- retractall(thr_offset(_, _)), retractall(thr_factor(_, _)), assertz(thr_offset(Name, D)).
set_perturbation(Name, factor, F) :- retractall(thr_offset(_, _)), retractall(thr_factor(_, _)), assertz(thr_factor(Name, F)).
clear_perturbation :- retractall(thr_offset(_, _)), retractall(thr_factor(_, _)).

exact_on(Mode, Split, E) :-
    clear_symptom_cache,
    findall(C, case_split(C, Split), Cases),
    aggregate_all(count, ( member(C, Cases), expected(C, E0), msort(E0, S),
                           diagnose_mode(Mode, C, G0), msort(G0, S) ), Ok),
    length(Cases, N),
    E is Ok / N.

threshold_sweep(File) :-
    Split = holdout,
    clear_perturbation,
    exact_on(deductive, Split, BD),
    exact_on(full, Split, BF),
    findall(row(Name, Kind, Unit, Base, Src, DDs, DFs),
            ( perturbable(Name, Kind),
              threshold(Name, Base, Unit, Src0), source(Src0, Src, _),
              levels(Kind, Ls),
              findall(DD-DF, ( member(L, Ls),
                               set_perturbation(Name, Kind, L),
                               exact_on(deductive, Split, ED), DD is (ED - BD) * 100,
                               exact_on(full, Split, EF), DF is (EF - BF) * 100 ), Pairs),
              clear_perturbation,
              pairs_keys_values(Pairs, DDs, DFs) ),
            Rows),
    clear_perturbation,
    clear_symptom_cache,
    setup_call_cleanup(open(File, write, S, [encoding(utf8)]),
                       write_threshold_tables(S, BD, BF, Rows),
                       close(S)),
    format("Wrote ~w~n", [File]).

write_threshold_tables(S, BD, BF, Rows) :-
    format(S, "# Stage 14: Threshold Sensitivity~n~n", []),
    format(S, "Generated by `tests/sensitivity.pl` on the held-out split. Do not edit by hand.~n~n", []),
    format(S, "Each threshold is perturbed on its own while all others keep their base values. Temperature thresholds move by -2, -1, +1 and +2 K. Other thresholds are scaled by 0.8, 0.9, 1.1 and 1.2. Each cell is the change in exact-match accuracy in percentage points. A dot means no change.~n~n", []),
    format(S, "Base exact match: deductive only ~1f%, complete system ~1f%.~n", [BD*100, BF*100]),
    forall(member(Which-Title, [ded-'Deductive only', full-'Complete system']),
           ( format(S, "~n## ~w~n~n| Threshold | Base | Source type | -2 K or x0.8 | -1 K or x0.9 | +1 K or x1.1 | +2 K or x1.2 | Worst |~n|---|---|---|---|---|---|---|---|~n", [Title]),
             forall(member(row(N, _, U, B, Src, DDs, DFs), Rows),
                    ( ( Which == ded -> Ds = DDs ; Ds = DFs ),
                      maplist(cell, Ds, Cs), min_list(Ds, W), cell(W, WC),
                      atomic_list_concat(Cs, ' | ', Row),
                      format(S, "| ~w | ~w ~w | ~w | ~w | ~w |~n", [N, B, U, Src, Row, WC]) )) )),
    format(S, "~nThresholds whose perturbation never changes the result are either far from every case's evidence, or are backed up by other rules or symptoms.~n", []).

cell(D, '.') :- abs(D) < 0.05, !.
cell(D, C) :- format(atom(C), "~1f", [D]).
