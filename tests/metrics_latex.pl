/*  tests/metrics_latex.pl - writes the evaluation results as LaTeX tables
    for the report, from one run of all four reasoning modes on both splits.
    Also rewrites the Markdown report, so both always agree.

    Run from the project folder:
        swipl -g "evaluation_all('docs/08_evaluation_results.md', 'report/tables')" -t halt main.pl tests/metrics.pl tests/metrics_latex.pl
*/

evaluation_all(MdFile, Dir) :-
    modes(Ms),
    findall(Sp-M-Rs, ( member(Sp, [calibration, holdout]), member(M, Ms), run_mode(M, Sp, Rs) ), All),
    setup_call_cleanup(open(MdFile, write, S0, [encoding(utf8)]), write_report(S0, All), close(S0)),
    make_directory_path(Dir),
    forall(member(Sp, [holdout, calibration]),
           ( atom_concat('eval_modes_', Sp, B1), atom_concat(B1, '.tex', F1),
             tex_file(Dir, F1, [S]>>tex_mode_table(S, All, Sp)),
             atom_concat('eval_categories_', Sp, B2), atom_concat(B2, '.tex', F2),
             tex_file(Dir, F2, [S]>>tex_category_table(S, All, Sp)) )),
    member(holdout-full-RsF, All), !,
    tex_file(Dir, 'eval_classes.tex', [S]>>tex_class_table(S, RsF)),
    tex_file(Dir, 'eval_confusion.tex', [S]>>tex_confusion_table(S, RsF)),
    format("Wrote ~w and LaTeX tables in ~w~n", [MdFile, Dir]),
    write_summary(user_output, All).

tex_file(Dir, Name, Writer) :-
    directory_file_path(Dir, Name, File),
    setup_call_cleanup(open(File, write, S, [encoding(utf8)]),
                       ( format(S, "% Generated by tests/metrics_latex.pl. Do not edit by hand.~n", []),
                         call(Writer, S) ),
                       close(S)).

split_name(holdout, 'held-out').
split_name(calibration, 'calibration').

pct(X, A) :- format(atom(A), "~1f\\%", [X * 100]).

tex_mode_table(S, All, Sp) :-
    split_name(Sp, SpN),
    format(S, "\\begin{table}[htbp]~n  \\centering~n  \\footnotesize~n  \\setlength{\\tabcolsep}{4pt}~n", []),
    format(S, "  \\caption{Comparison of reasoning modes, ~w split (255 cases). Class acc.: mean class accuracy. Explain.: ExplainabilityRate. Plan val.: PlanValidity.}~n  \\label{tab:modes-~w}~n", [SpN, Sp]),
    format(S, "  \\begin{tabular}{L{3.4cm}rrrrrrr}~n  \\toprule~n", []),
    format(S, "  Mode & Exact & Coverage & Macro F1 & Class acc. & Mean ms & Explain. & Plan val. \\\\~n  \\midrule~n", []),
    forall(member(Sp-M-Rs, All),
           ( mode_name(M, Name),
             emr(Rs, E), coverage(Rs, Cv), macro_prf(Rs, _, _, F), mean_class_accuracy(Rs, A),
             times(Rs, Tm, _), explainability_rate(Rs, X), plan_validity(Rs, PV),
             maplist(pct, [E, Cv, A, X, PV], [Ep, Cvp, Ap, Xp, PVp]),
             format(S, "  ~w & ~w & ~w & ~3f & ~w & ~2f & ~w & ~w \\\\~n", [Name, Ep, Cvp, F, Ap, Tm, Xp, PVp]) )),
    format(S, "  \\bottomrule~n  \\end{tabular}~n\\end{table}~n", []).

tex_category_table(S, All, Sp) :-
    split_name(Sp, SpN),
    modes(Ms),
    format(S, "\\begin{table}[htbp]~n  \\centering~n  \\small~n", []),
    format(S, "  \\caption{Exact matches by test category and reasoning mode, ~w split.}~n  \\label{tab:categories-~w}~n", [SpN, Sp]),
    format(S, "  \\begin{tabular}{L{3.2cm}L{1.0cm}L{1.0cm}rrrr}~n  \\toprule~n", []),
    format(S, "  Category & Test & Cases & Deductive & Ded.\\ + abd. & Ded.\\ + cons. & Complete \\\\~n  \\midrule~n", []),
    forall(category_info(Cat, Label, Test),
           ( member(Sp-deductive-R0, All),
             include([r(_, K, _, _, _)]>>(K == Cat), R0, In0), length(In0, N),
             findall(Cell, ( member(M, Ms), member(Sp-M-Rs, All),
                             include([r(_, K, E, G, _)]>>(K == Cat, E == G), Rs, Ok),
                             length(Ok, P), format(atom(Cell), "~d", [P]) ), Cells),
             atomic_list_concat(Cells, ' & ', Row),
             format(S, "  ~w & ~w & ~d & ~w \\\\~n", [Label, Test, N, Row]) )),
    format(S, "  \\bottomrule~n  \\end{tabular}~n\\end{table}~n", []).

