tex_confusion_table(S, Rs) :-
    true_classes(Ks),
    append(Ks, [multiple, unexplained_abnormality], Cols),
    length(Cols, NC),
    findall(H, ( member(K, Cols), col_head(K, H) ), Hs),
    atomic_list_concat(Hs, ' & ', Header),
    format(S, "\\begin{table}[htbp]~n  \\centering~n  \\small~n", []),
    format(S, "  \\caption{Confusion matrix of the complete system, held-out split, single-label cases (normal, single-fault and instrumentation categories). Rows are the true class and columns the predicted class. \\emph{Mult.}\\ means more than one label was predicted and \\emph{Unex.}\\ an unexplained abnormality.}~n  \\label{tab:confusion}~n", []),
    format(S, "  \\setlength{\\tabcolsep}{4pt}~n  \\begin{tabular}{l*{~d}{c}}~n  \\toprule~n", [NC]),
    format(S, "  True $\\backslash$ predicted & ~w \\\\~n  \\midrule~n", [Header]),
    include([r(_, Cat, [_], _, _)]>>memberchk(Cat, [normal, single_fault, instrumentation]), Rs, Singles),
    forall(member(K, Ks),
           ( findall(Cell, ( member(P, Cols),
                             aggregate_all(count, ( member(r(_, _, [L], G, _), Singles), label_class(L, K),
                                                    predicted_class(G, P) ), N),
                             ( N =:= 0 -> Cell = '$\\cdot$' ; format(atom(Cell), "~d", [N]) ) ), Cells),
             atomic_list_concat(Cells, ' & ', Row),
             col_head(K, KH),
             format(S, "  ~w & ~w \\\\~n", [KH, Row]) )),
    format(S, "  \\bottomrule~n  \\end{tabular}~n\\end{table}~n", []).
