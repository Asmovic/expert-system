"""Sensitivity to the reasoning parameters set by judgement (review item B4).

Run from the project folder:

    python tests/param_sensitivity.py     # about a minute

Each parameter in engine/params.pl is changed alone, and the three
model-based modes are run on the calibration and held-out splits and on
four stress sets from the sensitivity analysis: four times the nominal
noise, 20% of readings missing, four simultaneous faults, and a 2 K
sensor bias. Deduction uses
none of these parameters and is shown once as the reference.

Writes docs/15_parameter_sensitivity.md and report/tables/param_sensitivity.tex,
and prints the exact-match counts as JSON for tests/reproduce.py.
"""

import json
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BS = chr(92)

DATASETS = [
    # key, label, data file to load (None: already loaded by main.pl), split
    ("calibration", "Calibration", None, "calibration"),
    ("holdout", "Held-out", None, "holdout"),
    ("noise_4", "Noise ×4", "data/sweeps/noise_4.pl", "sweep"),
    ("missing_0p2", "20% missing", "data/sweeps/missing_0p2.pl", "sweep"),
    ("multi_4", "Four faults", "data/sweeps/multi_4.pl", "sweep"),
    ("bias_2p0", "2 K bias", "data/sweeps/bias_2p0.pl", "sweep"),
]

# variant -> (parameter, value shown)
VARIANTS = {
    "default": ("All at default", ""),
    "bonus_0": ("Deductive bonus", "0"), "bonus_005": ("Deductive bonus", "0.05"),
    "bonus_02": ("Deductive bonus", "0.2"), "bonus_05": ("Deductive bonus", "0.5"),
    "sigma_05": ("Evidence cut-off, $k\\sigma$", "0.5"), "sigma_15": ("Evidence cut-off, $k\\sigma$", "1.5"),
    "sigma_20": ("Evidence cut-off, $k\\sigma$", "2.0"),
    "bound_2": ("Search bound", "2"), "bound_3": ("Search bound", "3"), "bound_5": ("Search bound", "5"),
    "weights_uniform": ("Causal weights", "all 1"),
    "weights_p": ("Causal weights", "×U[0.5, 1.5], 5 draws"),
    "noise_fixed": ("Noise of unredundant features", "fixed"),
}
DEFAULTS = {"Deductive bonus": "0.1", "Evidence cut-off, $k\\sigma$": "1.0", "Search bound": "4",
            "Causal weights": "kb/causal.pl", "Noise of unredundant features": "tied to $\\sigma_T$"}
TEX_PARAM = {"Deductive bonus": "Deductive bonus", "Evidence cut-off, $k\\sigma$": "Cut-off $k$",
             "Search bound": "Search bound", "Causal weights": "Causal weights",
             "Noise of unredundant features": "Noise scaling"}
MODES = ["ded_abd", "ded_cbd", "full"]
MODE_SHORT = {"ded_abd": "D+A", "ded_cbd": "D+C", "full": "Full"}


def swipl():
    exe = shutil.which("swipl") or r"C:\Program Files\swipl\bin\swipl.exe"
    if not os.path.exists(exe) and not shutil.which("swipl"):
        sys.exit("swipl not found")
    return exe


def run(dataset):
    key, _, data, split = dataset
    goals = ([f"load_files(['{data}'], [])"] if data else []) + [f"param_sweep({split})"]
    cmd = [swipl(), "-q"]
    for g in goals:
        cmd += ["-g", g]
    cmd += ["-t", "halt", "main.pl", "tests/param_sensitivity.pl"]
    out = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, check=True).stdout
    rows = {}
    for line in out.splitlines():
        if line.startswith("JSON "):
            r = json.loads(line[5:])
            rows[(r["variant"], r["mode"])] = (r["correct"], r["n"])
    return key, rows


def collect():
    with ThreadPoolExecutor(max_workers=len(DATASETS)) as ex:
        return dict(ex.map(run, DATASETS))


def cell(res, ds, variant, mode):
    """Exact match in %, and the change from the default in cases."""
    if variant == "weights_p":
        ks = [res[ds][(f"weights_p{i}", mode)][0] for i in range(1, 6)]
        n = res[ds][(f"weights_p1", mode)][1]
        base = res[ds][("default", mode)][0]
        lo, hi = min(ks) - base, max(ks) - base
        return None, n, (lo, hi)
    k, n = res[ds][(variant, mode)]
    base = res[ds][("default", mode)][0]
    return k, n, (k - base, k - base)


def delta_text(lo, hi):
    f = lambda d: f"{d:+d}" if d else "0"
    return f(lo) if lo == hi else f"{f(lo)} to {f(hi)}"


def range_tex(lo, hi):
    f = lambda d: (f"{d:+d}" if d else "0").replace("-", "$-$")
    return f(lo) if lo == hi else f"[{f(lo)},{f(hi)}]"


def write_outputs(res):
    md = ["# Sensitivity to the Reasoning Parameters", "",
          "Generated by `tests/param_sensitivity.py`. Do not edit by hand. Every case is synthetic.", "",
          "Each parameter of `engine/params.pl` is changed alone. Cells give the change in exactly matched cases "
          "against the defaults, for deductive + abductive / deductive + consistency-based / complete system. "
          "The first two rows give the exact-match counts at the defaults. Defaults: deductive bonus 0.1, "
          "evidence cut-off k = 1, search bound 4, causal weights from `kb/causal.pl`, noise of unredundant features "
          "tied to the estimated temperature-sensor noise.", ""]
    head = "| Parameter | Value | " + " | ".join(lbl for _, lbl, _, _ in DATASETS) + " |"
    md += [head, "|---" * (len(DATASETS) + 2) + "|"]
    ref = "| Deduction only (reference) | | " + " | ".join(
        "{} of {}".format(*res[k][("default", "deductive")]) for k, _, _, _ in DATASETS) + " |"
    for v, (param, val) in VARIANTS.items():
        cells = []
        for k, _, _, _ in DATASETS:
            if v == "default":
                cells.append(" / ".join(str(res[k][("default", m)][0]) for m in MODES) + f" of {res[k][('default', 'full')][1]}")
            else:
                cells.append(" / ".join(delta_text(*cell(res, k, v, m)[2]) for m in MODES))
        shown = val if v != "default" else "defaults"
        md.append(f"| {param.replace('$k' + BS + 'sigma$', 'k sigma')} | {shown} | " + " | ".join(cells) + " |")
    md.insert(md.index(head) + 2, ref)
    md += ["", "## Raw counts", "", "| Dataset | Variant | Mode | Correct | Cases |", "|---|---|---|---|---|"]
    for k, _, _, _ in DATASETS:
        for (v, m), (c, n) in sorted(res[k].items()):
            md.append(f"| {k} | {v} | {m} | {c} | {n} |")
    with open(os.path.join(ROOT, "docs", "15_parameter_sensitivity.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(md) + "\n")

    tex = ["% Generated by tests/param_sensitivity.py. Do not edit by hand.",
           f"{BS}begin{{table}}[htbp]", f"  {BS}centering", f"  {BS}scriptsize", f"  {BS}setlength{{{BS}tabcolsep}}{{3pt}}",
           f"  {BS}caption{{Sensitivity to the reasoning parameters set by judgement. Each parameter is changed alone. "
           f"The first two rows give exactly matched cases at the defaults; the other rows give the change in exactly "
           f"matched cases, for deductive + abductive / deductive + consistency-based / complete system. For the perturbed "
           f"weights, the range over five random draws is given in brackets. Defaults: bonus 0.1, cut-off $k = 1$, search bound 4, "
           f"weights from {BS}texttt{{kb/causal.pl}}, noise of unredundant features tied to $" + BS + "sigma_T$. "
           f"Raw counts are in {BS}texttt{{docs/15{BS}_parameter{BS}_sensitivity.md}}.}}",
           f"  {BS}label{{tab:param-sensitivity}}",
           f"  {BS}begin{{tabular}}{{L{{2.3cm}}l" + "c" * len(DATASETS) + "}", f"  {BS}toprule",
           "  Parameter & Value & " + " & ".join(lbl.replace("%", BS + "%").replace("×", "$" + BS + "times$")
                                               for _, lbl, _, _ in DATASETS) + f" {BS}{BS}",
           f"  {BS}midrule",
           "  Deduction only & & " + " & ".join(str(res[k][("default", "deductive")][0]) for k, _, _, _ in DATASETS) + f" {BS}{BS}",
           "  Model-based & default & " + " & ".join("/".join(str(res[k][("default", m)][0]) for m in MODES)
                                                     for k, _, _, _ in DATASETS) + f" {BS}{BS}",
           f"  {BS}midrule"]
    last = None
    for v, (param, val) in VARIANTS.items():
        if v == "default":
            continue
        if last and param != last:
            tex.append(f"  {BS}addlinespace")
        shown_param = TEX_PARAM[param] if param != last else ""
        last = param
        val_tex = val.replace("×", "$" + BS + "times$").replace("U[0.5, 1.5], 5 draws", "U[.5,1.5]")
        cells = ["/".join(range_tex(*cell(res, k, v, m)[2]) for m in MODES)
                 for k, _, _, _ in DATASETS]
        tex.append(f"  {shown_param} & {val_tex} & " + " & ".join(cells) + f" {BS}{BS}")
    tex += [f"  {BS}bottomrule", f"  {BS}end{{tabular}}", f"{BS}end{{table}}", ""]
    with open(os.path.join(ROOT, "report", "tables", "param_sensitivity.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(tex))


def main():
    res = collect()
    write_outputs(res)
    summary = {k: {f"{v}|{m}": c for (v, m), (c, _) in rows.items()} for k, rows in res.items()}
    print("JSON " + json.dumps(summary, sort_keys=True))


if __name__ == "__main__":
    main()
